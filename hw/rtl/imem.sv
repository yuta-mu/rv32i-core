// 命令メモリ: アドレスを受け取り，そこに保存された命令を出力する

module imem (
    input  logic [31:0] a,   // PCから送られてくるアドレス
    output logic [31:0] rd   // 読み出された32ビットの命令
);

    // 32ビット(4バイト)の箱を64個（合計256バイトのメモリ）
    logic [31:0] RAM[0:63];

    initial begin
        // テスト用に予め命令（16進数）をセット
        RAM[0] = 32'h11111111;
        RAM[1] = 32'h22222222;
        RAM[2] = 32'h33333333;
    end

    // アドレスを4で割ってメモリのインデックスに変換
    assign rd = RAM[a[7:2]];
    // MMUなしなので，アドレスの上位ビットは無視...

endmodule